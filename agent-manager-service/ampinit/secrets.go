// Secret is a secret generated on first run and kept in the secrets
// directory, unless its setting is set.
type Secret struct {
	Setting string
	// Shared secrets are read by other containers (ThunderID's setup,
	// PostgreSQL), so a set value is written too, and each is copied to
	// AMP_SHARED_SECRETS_DIR, the only directory those containers mount.
	Shared bool
	// Dir names the setting whose directory holds the secret instead of the
	// secrets directory, for a secret the server must not read. A set value
	// is written too; with Dir unset, the secret is skipped.
	Dir string
	// CopyTo names settings whose directories each get a copy (0644), each
	// mounted only by the containers that read the secret.
	CopyTo []string
	// ServeOnly secrets are generated by amp serve, which can tell a new
	// install from an existing one.
	ServeOnly bool
	// When reports whether the secret is needed; nil means always.
	When func() bool
	Gen  func() ([]byte, error)
}

// Secrets are the secrets amp generates.
var Secrets = []Secret{
	{Setting: "ENCRYPTION_KEY", ServeOnly: true, Gen: randomHex(32)},
	{Setting: "IDP_CLIENT_SECRET", Gen: randomToken(32)},
	{Setting: "AMP_CONSOLE_CLIENT_SECRET", Gen: randomToken(32)},
	{Setting: "THUNDER_CLIENT_SECRET", Gen: randomToken(32)},
	{Setting: "AMP_ADMIN_PASSWORD", Shared: true, Gen: randomPassword(24)},
	{Setting: "MODULE_AI_GATEWAY_ADMIN_PASSWORD", Gen: randomPassword(24)},
	{Setting: "DB_PASSWORD", Shared: true, When: usesPostgres, Gen: randomPassword(24)},
	// The observability store's logins: ClickHouse holds all four, and each
	// other reader gets a copy of its own only.
	{Setting: "MODULE_OBSERVABILITY_CLICKHOUSE_PASSWORD", Dir: ClickHouseSecretsDir, CopyTo: []string{ClickHouseAPISecretsDir}, When: usesObservability, Gen: randomPassword(24)},
	{Setting: "MODULE_OBSERVABILITY_CLICKHOUSE_CLEANER_PASSWORD", Dir: ClickHouseSecretsDir, CopyTo: []string{ClickHouseAPISecretsDir}, When: usesObservability, Gen: randomPassword(24)},
	{Setting: "MODULE_OBSERVABILITY_CLICKHOUSE_MIGRATOR_PASSWORD", Dir: ClickHouseSecretsDir, CopyTo: []string{ClickHouseMigrateSecretsDir}, When: usesObservability, Gen: randomPassword(24)},
	{Setting: "MODULE_OBSERVABILITY_CLICKHOUSE_INGEST_PASSWORD", Dir: ClickHouseSecretsDir, CopyTo: []string{ClickHouseCollectorSecretsDir}, When: usesObservability, Gen: randomPassword(24)},
}

// The settings naming where the observability store's passwords are written.
const (
	// ClickHouseSecretsDir holds all four, for ClickHouse.
	ClickHouseSecretsDir = "AMP_CLICKHOUSE_SECRETS_DIR"
	// ClickHouseAPISecretsDir gets the read and delete passwords, for the server.
	ClickHouseAPISecretsDir = "AMP_CLICKHOUSE_API_SECRETS_DIR"
	// ClickHouseMigrateSecretsDir gets the setup password, for amp migrate.
	ClickHouseMigrateSecretsDir = "AMP_CLICKHOUSE_MIGRATE_SECRETS_DIR"
	// ClickHouseCollectorSecretsDir gets the write password, for the collector.
	ClickHouseCollectorSecretsDir = "AMP_CLICKHOUSE_COLLECTOR_SECRETS_DIR"
)

// EnsureSecrets writes into dir each secret amp init generates: kept if its
// file exists, skipped if its setting is set (a shared secret's set value is
// written instead), else generated.
func EnsureSecrets(dir string, owner *initfiles.Owner) error {
	if err := initfiles.ChownDir(dir, owner); err != nil {
		return err
	}
	for _, s := range Secrets {
		if s.ServeOnly || (s.When != nil && !s.When()) {
			continue
		}
		if err := ensureSecret(dir, s, owner); err != nil {
			return fmt.Errorf("%s: %w", s.Setting, err)
		}
	}
	return nil
}

// ensureSecret writes one secret into dir, or its own Dir, as EnsureSecrets
// does.
func ensureSecret(dir string, s Secret, owner *initfiles.Owner) error {
	if s.Dir != "" {
		if dir = strings.TrimSpace(config.Value(s.Dir)); dir == "" {
			return nil
		}
	}
	name := config.GeneratedSecrets[s.Setting]
	path := filepath.Join(dir, name)
	var value []byte
	if set := config.SetValue(s.Setting); set != "" {
		if !s.Shared && s.Dir == "" {
			return nil
		}
		value = []byte(set)
		if err := initfiles.WriteFile(path, value, 0o600, owner); err != nil {
			return err
		}
	} else {
		if _, err := os.Stat(path); err != nil {
			slog.Info("Generating a secret", "setting", s.Setting, "file", path)
		}
		var err error
		if value, err = initfiles.WriteOnce(path, 0o600, owner, s.Gen); err != nil {
			return err
		}
	}
	return copySecret(s, name, value, owner)
}

// copySecret writes a secret's copies: into AMP_SHARED_SECRETS_DIR when it is
// shared, and into each CopyTo directory that is set.
func copySecret(s Secret, name string, value []byte, owner *initfiles.Owner) error {
	targets := s.CopyTo
	if s.Shared {
		targets = append([]string{"AMP_SHARED_SECRETS_DIR"}, targets...)
	}
	for _, setting := range targets {
		dir := strings.TrimSpace(config.Value(setting))
		if dir == "" {
			continue
		}
		// Readable by the other containers' users; the directory holds nothing else.
		if err := initfiles.WriteFile(filepath.Join(dir, name), value, 0o644, owner); err != nil {
			return err
		}
	}
	return nil
}

// usesObservability reports whether the observability module has a store.
func usesObservability() bool {
	return strings.TrimSpace(config.Value(config.ModuleConfigKey("observability", "clickhouse.url"))) != ""
}

func usesPostgres() bool {
	driver := strings.ToLower(strings.TrimSpace(config.Value("DB_DRIVER")))
	if driver == "" && strings.TrimSpace(config.Value("DB_HOST")) != "" {
		driver = config.DBDriverPostgres
	}
	return driver == config.DBDriverPostgres
}

func randomBytes(n int) ([]byte, error) {
	b := make([]byte, n)
	_, err := rand.Read(b)
	return b, err
}

func randomHex(n int) func() ([]byte, error) {
	return func() ([]byte, error) {
		b, err := randomBytes(n)
		return []byte(hex.EncodeToString(b)), err
	}
}

func randomToken(n int) func() ([]byte, error) {
	return func() ([]byte, error) {
		b, err := randomBytes(n)
		return []byte(base64.RawURLEncoding.EncodeToString(b)), err
	}
}

const passwordAlphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"

func randomPassword(n int) func() ([]byte, error) {
	return func() ([]byte, error) {
		out := make([]byte, n)
		limit := big.NewInt(int64(len(passwordAlphabet)))
		for i := range out {
			j, err := rand.Int(rand.Reader, limit)
			if err != nil {
				return nil, err
			}
			out[i] = passwordAlphabet[j.Int64()]
		}
		return out, nil
	}
}

// EnsureServeSecret writes the secret amp serve generates for setting into
// dir, as EnsureSecrets does, when it is not set; it reports whether the
// secret was set or kept rather than generated.
func EnsureServeSecret(dir, setting string, owner *initfiles.Owner) error {
	for _, s := range Secrets {
		if s.Setting == setting {
			return ensureSecret(dir, s, owner)
		}
	}
	return fmt.Errorf("%s is not a generated secret", setting)
}
