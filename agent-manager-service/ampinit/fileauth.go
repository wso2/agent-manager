package ampinit

import (
	"fmt"
	"path/filepath"
	"strings"

	"golang.org/x/crypto/bcrypt"
	"gopkg.in/yaml.v3"

	"github.com/wso2/agent-manager/agent-manager-service/rbac"
)

// FileAuthUsersFile is the user file's name inside the output directory.
const FileAuthUsersFile = "users.yaml"

// bcryptCost for the generated hashes. 12 is the usual floor for a password
// store; the cost is paid once here and once per sign-in, never in a loop.
const bcryptCost = 12

// FileAuthConfig is everything the file-based user file depends on.
//
// The accounts are the same ones ThunderID is seeded with, read from the same
// AMP_DEFAULT_USERS, so the two sign-in modes have the same logins and
// switching between them does not change who can get in.
type FileAuthConfig struct {
	// OrgUUID is the organization's id, stamped as the ouId claim. It must be a
	// UUID: the control plane creates the organization and its default
	// environment on first use, keyed by this value (repositories.ensureOrg).
	OrgUUID string
	// OrgHandle is stamped as ouHandle and becomes the organization's handle
	// when that row is created.
	OrgHandle string
	Users     []User
}

// userEntry is one account as the user file spells it.
type userEntry struct {
	Username     string   `yaml:"username"`
	PasswordHash string   `yaml:"passwordHash"`
	Roles        []string `yaml:"roles"`
}

type usersDocument struct {
	Organization struct {
		Handle string `yaml:"handle"`
		UUID   string `yaml:"uuid"`
	} `yaml:"organization"`
	Users []userEntry `yaml:"users"`
}

// WriteFileAuth writes the file-based user file into dir.
//
// It is rewritten on every run rather than kept, so AMP_DEFAULT_USERS in .env
// stays the one place accounts are declared. Keeping the first version instead
// would silently ignore a password an operator had just changed — and bcrypt
// salts afresh each time, so a kept file could not be compared against the
// environment to notice the difference.
func WriteFileAuth(cfg *FileAuthConfig, dir string) error {
	ampOwner, err := parseOwner("AMP_FILE_OWNER")
	if err != nil {
		return err
	}
	if err := chownDir(dir, ampOwner); err != nil {
		return err
	}

	doc := usersDocument{}
	doc.Organization.Handle = cfg.OrgHandle
	doc.Organization.UUID = cfg.OrgUUID

	for _, u := range cfg.Users {
		hash, err := bcrypt.GenerateFromPassword([]byte(u.Password), bcryptCost)
		if err != nil {
			return fmt.Errorf("hashing the password for %q: %w", u.Username, err)
		}
		doc.Users = append(doc.Users, userEntry{
			Username:     u.Username,
			PasswordHash: string(hash),
			Roles:        []string{roleFor(u)},
		})
	}

	body, err := yaml.Marshal(doc)
	if err != nil {
		return fmt.Errorf("rendering %s: %w", FileAuthUsersFile, err)
	}
	header := "# Generated by amp-init from AMP_DEFAULT_USERS. Edits are overwritten\n" +
		"# on the next start; change AMP_DEFAULT_USERS in .env instead.\n" +
		"#\n" +
		"# This file holds every operator's password hash. Treat it as a secret.\n"

	// 0600: readable only by the account the API runs as.
	return writeFile(filepath.Join(dir, FileAuthUsersFile), append([]byte(header), body...), 0o600, ampOwner)
}

// roleFor maps the one bit AMP_DEFAULT_USERS carries onto a role the catalog
// declares. The file names roles rather than scopes, so the scopes a token
// carries follow rbac.PredefinedRolePermissions and cannot drift from it.
func roleFor(u User) string {
	if u.Admin {
		return rbac.RoleAdmin
	}
	return rbac.RoleDeveloper
}

// defaultOrgHandle is the handle an organization gets when none is configured.
const defaultOrgHandle = "default"

// normaliseHandle keeps the handle within what the control plane accepts.
func normaliseHandle(handle string) string {
	handle = strings.ToLower(strings.TrimSpace(handle))
	if handle == "" {
		return defaultOrgHandle
	}
	return handle
}
