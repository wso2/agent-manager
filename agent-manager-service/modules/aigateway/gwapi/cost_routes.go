// RegisterCostRoutes registers the AI cost route.
func RegisterCostRoutes(rr Router, controller gwctl.CostController) {
	rr.HandleFuncWithValidationAndAuthz("GET /orgs/{orgName}/costs", gwperm.CostRead, controller.GetCosts)
}
