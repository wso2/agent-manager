# Generates the Go types of an OpenAPI document.
#
#   gen_client.sh                       the core's document into spec/ (package spec)
#   gen_client.sh INPUT OUTPUT PACKAGE  another document, such as a module's own
#                                       (modules/<dir>/api/openapi.yaml), into OUTPUT
set -e

INPUT="${1:-docs/api_v1_openapi.yaml}"
OUT="${2:-spec}"
PKG="${3:-spec}"

# OUT is wiped first: it must be a directory of this module, never empty,
# absolute or reaching out of it.
case "$OUT" in
    "" | /* | *..* | . | ./)
        echo "gen_client.sh: refusing output directory '$OUT'" >&2
        exit 1
        ;;
esac

rm -rf "./$OUT"
mkdir -p "./$OUT"
cp scripts/.openapi-generator-ignore "./$OUT/.openapi-generator-ignore"
# Remove tags from the openapi file to prevent changing output based on tags
npx openapi-format "$INPUT" -o "./$OUT/api_v1_openapi.yaml"

export GO_POST_PROCESS_FILE="$(which gofmt) -w"

OPENAPI_GENERATOR_VERSION="7.0.0"

if [ "$CI" = "true" ]; then
    # In CI, use the JAR directly to avoid Docker Hub rate limits
    OPENAPI_GENERATOR_JAR="/tmp/openapi-generator-cli-${OPENAPI_GENERATOR_VERSION}.jar"
    if [ ! -f "$OPENAPI_GENERATOR_JAR" ]; then
        curl -sL "https://repo1.maven.org/maven2/org/openapitools/openapi-generator-cli/${OPENAPI_GENERATOR_VERSION}/openapi-generator-cli-${OPENAPI_GENERATOR_VERSION}.jar" \
            -o "$OPENAPI_GENERATOR_JAR"
    fi

    java -jar "$OPENAPI_GENERATOR_JAR" generate \
        -i "$OUT/api_v1_openapi.yaml" \
        -g go \
        -o "$OUT" \
        --package-name "$PKG" \
        --schema-mappings MetricDateTime=string \
        --additional-properties enumClassPrefix=true \
        --enable-post-process-file
else
    # Locally, use Docker
    USER_ID=$(id -u)
    GROUP_ID=$(id -g)

    docker run --rm -v "${PWD}:/local" -e GO_POST_PROCESS_FILE="/usr/local/bin/gofmt -w" \
        -u $USER_ID:$GROUP_ID \
        "openapitools/openapi-generator-cli:v${OPENAPI_GENERATOR_VERSION}" generate \
        -i "/local/$OUT/api_v1_openapi.yaml" \
        -g go \
        -o "/local/$OUT" \
        --package-name "$PKG" \
        --schema-mappings MetricDateTime=string \
        --additional-properties enumClassPrefix=true
fi

rm "./$OUT/.openapi-generator-ignore"
rm "./$OUT/api_v1_openapi.yaml"
rm -rf "./$OUT/.openapi-generator"
rm -rf "./$OUT/api"
rm -rf "./$OUT/README.md"
rm -rf "./$OUT/test"
rm -f "./$OUT"/**/*_test.go

cat <<EOF >"./$OUT/type_aliases.go"
// Code generated by generate_api_client.sh script; DO NOT EDIT.

package $PKG

// defined type aliases here so that we can specify the custom types in api schema
// without having to add imports in auto-generated code
type MetricDateTime = string
EOF
