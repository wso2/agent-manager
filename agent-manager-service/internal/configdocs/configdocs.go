// Package configdocs renders the configuration reference
// (docs/amp-lite/configuration.md) from config.Settings and the module
// manifests.
package configdocs

import (
	"fmt"
	"sort"
	"strings"

	"github.com/wso2/agent-manager/agent-manager-service/config"
	"github.com/wso2/agent-manager/agent-manager-service/modkit"
)

const intro = `# Configuration reference

<!-- Generated by ` + "`make config-docs`" + ` from agent-manager-service/config/settings.go and the module manifests. Do not edit. -->

Agent Manager reads each setting from, first found:

1. the environment variable of its name (even an empty one, except for a generated secret);
2. ` + "`<NAME>_FILE`" + ` in the environment, a file holding the value;
3. ` + "`amp.yaml`" + ` (` + "`--config`" + `, else ` + "`$AMP_CONFIG`" + `, else ` + "`./amp.yaml`" + `), where the name is nested by ` + "`_`" + `: ` + "`DB_HOST`" + ` is ` + "`db: {host: ...}`" + `, and ` + "`<key>_file`" + ` names a file;
4. its older name, where it has one;
5. for a generated secret, its file in the secrets directory (` + "`amp secret list`" + `);
6. its default.

A value in ` + "`amp.yaml`" + ` can be a reference: ` + "`${env:NAME}`" + ` or ` + "`${file:/path}`" + `, optionally with a default (` + "`${env:NAME:-default}`" + `). A reference that does not resolve stops startup only when ` + "`amp.yaml`" + `'s value is the one used, so the environment can override it. ` + "`amp serve`" + ` generates the secrets marked _generated_ on first run when nothing sets them, and keeps them; ` + "`amp init`" + ` generates them all except ` + "`ENCRYPTION_KEY`" + `, which only ` + "`amp serve`" + ` creates because it first checks that the database holds no data. For these secrets, an empty value or an empty file counts as unset. A generated secret's file that exists but cannot be read stops startup and is never replaced.
`

// Render returns the configuration reference page.
func Render() string {
	var b strings.Builder
	b.WriteString(intro)
	for _, group := range config.Groups {
		fmt.Fprintf(&b, "\n## %s\n\n", group)
		if group == "Console" {
			b.WriteString("`CONSOLE_<NAME>` fills `$NAME` in the console's `config.js`; unset, the API works out the value where it can.\n\n")
		}
		b.WriteString("| Setting | amp.yaml | Default | Description |\n|---|---|---|---|\n")
		for _, s := range config.Settings {
			if s.Group != group {
				continue
			}
			desc := s.Description
			if old := config.OldName(s.Key); old != "" {
				desc += fmt.Sprintf(" Also read as `%s`.", old)
			}
			if s.Secret {
				desc += " **Secret.**"
			}
			fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s |\n", s.Key, yamlPath(s.Key), code(s.Default), escape(desc))
		}
	}
	modules := modkit.Registered()
	sort.Slice(modules, func(i, j int) bool { return modules[i].Manifest().Name < modules[j].Manifest().Name })
	for _, m := range modules {
		man := m.Manifest()
		if len(man.Settings) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n## Module: %s\n\n", man.Name)
		fmt.Fprintf(&b, "Set as `%s<KEY>`, or under `config:` in the module's `modules:` entry in `amp.yaml`:\n\n", config.ModuleConfigKey(man.Name, ""))
		fmt.Fprintf(&b, "```yaml\nmodules:\n  - name: %s\n    config:\n      %s: ...\n```\n\n", man.Name, strings.ToLower(man.Settings[0].Key))
		b.WriteString("| Key | Variable | Default | Description |\n|---|---|---|---|\n")
		for _, s := range man.Settings {
			desc := s.Description
			if s.Secret {
				desc += " **Secret.**"
			}
			fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s |\n", strings.ToLower(s.Key), config.ModuleConfigKey(man.Name, s.Key), code(s.Default), escape(desc))
		}
	}
	return b.String()
}

// yamlPath is a setting's place in amp.yaml: its first word as the section.
func yamlPath(key string) string {
	k := strings.ToLower(key)
	section, rest, ok := strings.Cut(k, "_")
	if !ok {
		return k
	}
	return section + "." + rest
}

func code(v string) string {
	if v == "" {
		return ""
	}
	return "`" + strings.ReplaceAll(v, "|", "\\|") + "`"
}

func escape(s string) string { return strings.ReplaceAll(s, "|", "\\|") }
