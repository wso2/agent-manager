func (s *alertingService) GetEndpoint(ctx context.Context, ouID string) (*models.AlertEndpoint, error) {
	endpoint, err := s.alertRepo.GetEndpoint(ctx, ouID)
	if err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return nil, utils.ErrAlertEndpointNotFound
		}
		return nil, fmt.Errorf("failed to get alert endpoint: %w", err)
	}
	return endpoint, nil
}

func (s *alertingService) UpsertEndpoint(ctx context.Context, ouID string, in UpsertAlertEndpointInput) (*models.AlertEndpoint, string, error) {
	if ouID == "" {
		return nil, "", fmt.Errorf("%w: organization is required", utils.ErrInvalidInput)
	}
	if err := s.sender.ValidateURL(ctx, in.URL); err != nil {
		return nil, "", err
	}
	if in.Headers != nil {
		if len(in.Headers) > maxAlertHeaders {
			return nil, "", fmt.Errorf("%w: at most %d headers are allowed", utils.ErrInvalidInput, maxAlertHeaders)
		}
		if err := validateAlertHeaders(in.Headers); err != nil {
			return nil, "", err
		}
	}

	existing, err := s.alertRepo.GetEndpoint(ctx, ouID)
	if err != nil && !errors.Is(err, gorm.ErrRecordNotFound) {
		return nil, "", fmt.Errorf("failed to get alert endpoint: %w", err)
	}

	endpoint := &models.AlertEndpoint{
		OUID:        ouID,
		URL:         in.URL,
		Enabled:     in.Enabled,
		HeaderNames: []string{},
		CreatedAt:   s.now(),
	}
	if existing != nil {
		// Stored headers were entered for the old destination. Keeping them
		// across a move to another scheme or host would send its credentials
		// to a server they were never meant for, so they must be re-entered
		// (or cleared with an empty object).
		if in.Headers == nil && len(existing.HeaderNames) > 0 && alertEndpointOriginChanged(existing.URL, in.URL) {
			return nil, "", fmt.Errorf("%w: re-enter the request headers when changing the endpoint's host or scheme", utils.ErrInvalidInput)
		}
		endpoint = existing
		endpoint.URL = in.URL
		endpoint.Enabled = in.Enabled
	}

	if in.Headers != nil {
		names, encrypted, err := s.encryptHeaders(in.Headers)
		if err != nil {
			return nil, "", err
		}
		endpoint.HeaderNames = names
		endpoint.HeadersEncrypted = encrypted
	}

	newSecret := ""
	if existing == nil || in.RegenerateSigningSecret || len(endpoint.SigningSecretEncrypted) == 0 {
		newSecret, err = generateAlertSigningSecret()
		if err != nil {
			return nil, "", err
		}
		encrypted, err := utils.EncryptBytes([]byte(newSecret), s.encryptionKey)
		if err != nil {
			return nil, "", fmt.Errorf("failed to encrypt signing secret: %w", err)
		}
		endpoint.SigningSecretEncrypted = encrypted
	}

	// Fail closed: the endpoint carries credentials and decides where alert
	// data is sent, so it is not changed without a record of who changed it.
	attempt, err := audit.Begin(ctx, audit.ActionAlertEndpointConfigure,
		audit.Org(ouID),
		audit.Resource(audit.ResourceAlertEndpoint, ouID),
		// Scheme and host only: a webhook path can itself be the credential.
		audit.Detail("endpointUrl", alertEndpointOrigin(endpoint.URL)),
		audit.Detail("enabled", endpoint.Enabled),
		audit.Detail("headerNames", endpoint.HeaderNames),
		audit.Detail("secretRotated", newSecret != ""),
	)
	if err != nil {
		return nil, "", err
	}
	if err := s.alertRepo.UpsertEndpoint(ctx, endpoint); err != nil {
		attempt.Complete(ctx, err)
		return nil, "", fmt.Errorf("failed to save alert endpoint: %w", err)
	}
	attempt.Complete(ctx, nil)
	s.logger.Info("Alert endpoint saved", "ouID", ouID, "enabled", endpoint.Enabled, "secretRotated", newSecret != "")
	return endpoint, newSecret, nil
}

func (s *alertingService) DeleteEndpoint(ctx context.Context, ouID string) error {
	attempt, err := audit.Begin(ctx, audit.ActionAlertEndpointDelete,
		audit.Org(ouID),
		audit.Resource(audit.ResourceAlertEndpoint, ouID),
	)
	if err != nil {
		return err
	}
	deleted, err := s.alertRepo.DeleteEndpoint(ctx, ouID)
	if err != nil {
		attempt.Complete(ctx, err)
		return fmt.Errorf("failed to delete alert endpoint: %w", err)
	}
	if !deleted {
		attempt.Complete(ctx, utils.ErrAlertEndpointNotFound)
		return utils.ErrAlertEndpointNotFound
	}
	attempt.Complete(ctx, nil)
	s.logger.Info("Alert endpoint deleted", "ouID", ouID)
	return nil
}

func (s *alertingService) TestEndpoint(ctx context.Context, ouID string) (*AlertTestResult, error) {
	endpoint, err := s.GetEndpoint(ctx, ouID)
	if err != nil {
		return nil, err
	}
	target, err := s.resolveTarget(endpoint)
	if err != nil {
		return nil, err
	}
	event := models.AlertEvent{
		ID:         "evt_test_" + uuid.NewString(),
		Type:       models.AlertEventTest,
		Version:    alertEventVersion,
		OccurredAt: s.now().UTC(),
		Severity:   models.AlertSeverityInfo,
		OrgID:      ouID,
		Message:    "Test alert from WSO2 Agent Manager. No action is needed.",
	}
	body, err := json.Marshal(event)
	if err != nil {
		return nil, fmt.Errorf("failed to encode test alert: %w", err)
	}
	code, sendErr := s.sender.Send(ctx, target, event.ID, event.Type, body)
	result := &AlertTestResult{Delivered: sendErr == nil, StatusCode: code}
	if sendErr != nil {
		result.Error = sendErr.Error()
	}
	return result, nil
}

func (s *alertingService) ListDeliveries(ctx context.Context, ouID string, limit int) ([]models.AlertDelivery, error) {
	if limit <= 0 {
		limit = defaultDeliveryPageSize
	}
	limit = min(limit, maxDeliveryPageSize)
	deliveries, err := s.alertRepo.ListDeliveries(ctx, ouID, limit)
	if err != nil {
		return nil, fmt.Errorf("failed to list alert deliveries: %w", err)
	}
	return deliveries, nil
}

func (s *alertingService) encryptHeaders(headers map[string]string) ([]string, []byte, error) {
	names := make([]string, 0, len(headers))
	for name := range headers {
		names = append(names, name)
	}
	sort.Strings(names)
	if len(headers) == 0 {
		return names, nil, nil
	}
	raw, err := json.Marshal(headers)
	if err != nil {
		return nil, nil, fmt.Errorf("failed to encode headers: %w", err)
	}
	encrypted, err := utils.EncryptBytes(raw, s.encryptionKey)
	if err != nil {
		return nil, nil, fmt.Errorf("failed to encrypt headers: %w", err)
	}
	return names, encrypted, nil
}

// resolveTarget decrypts an endpoint's headers and signing secret.
func (s *alertingService) resolveTarget(endpoint *models.AlertEndpoint) (AlertTarget, error) {
	return resolveAlertTarget(endpoint, s.encryptionKey)
}

func resolveAlertTarget(endpoint *models.AlertEndpoint, key []byte) (AlertTarget, error) {
	target := AlertTarget{URL: endpoint.URL, Headers: map[string]string{}}
	secret, err := utils.DecryptBytes(endpoint.SigningSecretEncrypted, key)
	if err != nil {
		return AlertTarget{}, fmt.Errorf("failed to decrypt signing secret: %w", err)
	}
	target.SigningSecret = string(secret)
	if len(endpoint.HeadersEncrypted) > 0 {
		raw, err := utils.DecryptBytes(endpoint.HeadersEncrypted, key)
		if err != nil {
			return AlertTarget{}, fmt.Errorf("failed to decrypt headers: %w", err)
		}
		if err := json.Unmarshal(raw, &target.Headers); err != nil {
			return AlertTarget{}, fmt.Errorf("failed to decode headers: %w", err)
		}
	}
	return target, nil
}

// alertEndpointOriginChanged reports whether two endpoint URLs differ in
// scheme or host (including port). An unparsable URL counts as changed.
func alertEndpointOriginChanged(oldURL, newURL string) bool {
	o, oErr := url.Parse(oldURL)
	n, nErr := url.Parse(newURL)
	if oErr != nil || nErr != nil {
		return true
	}
	return !strings.EqualFold(o.Scheme, n.Scheme) || !strings.EqualFold(o.Host, n.Host)
}

// alertEndpointOrigin returns scheme://host for a URL, dropping the path and
// query where webhook providers often embed their secret.
func alertEndpointOrigin(raw string) string {
	u, err := url.Parse(raw)
	if err != nil || u.Host == "" {
		return ""
	}
	return u.Scheme + "://" + u.Host
}

func generateAlertSigningSecret() (string, error) {
	buf := make([]byte, alertSigningSecretBytes)
	if _, err := rand.Read(buf); err != nil {
		return "", fmt.Errorf("failed to generate signing secret: %w", err)
	}
	return alertSigningSecretPfx + hex.EncodeToString(buf), nil
}

// endpointEnabled reports whether the org has an endpoint alerts can go to.
func (s *alertingService) endpointEnabled(ctx context.Context, ouID string) (bool, error) {
	endpoint, err := s.alertRepo.GetEndpoint(ctx, ouID)
	if err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return false, nil
		}
		return false, fmt.Errorf("failed to get alert endpoint: %w", err)
	}
	return endpoint.Enabled, nil
}

