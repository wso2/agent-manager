func (s *alertingService) loadMonitor(ouID, projectName, agentName, monitorName string) (*models.Monitor, error) {
	monitor, err := s.monitorRepo.GetMonitorByName(ouID, projectName, agentName, monitorName)
	if err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return nil, utils.ErrMonitorNotFound
		}
		return nil, fmt.Errorf("failed to get monitor: %w", err)
	}
	// Defense in depth: the repository filters by org, but the caller's org
	// must also own the loaded row.
	if monitor.OUID != ouID {
		return nil, utils.ErrMonitorNotFound
	}
	return monitor, nil
}

func defaultMonitorAlertConfig(monitorID uuid.UUID) *models.MonitorAlertConfig {
	return &models.MonitorAlertConfig{
		MonitorID:           monitorID,
		Enabled:             false,
		AlertOnRunFailure:   true,
		Thresholds:          []models.MonitorAlertThreshold{},
		CooldownMinutes:     models.DefaultAlertCooldownMinutes,
		ConsecutiveBreaches: models.DefaultAlertConsecutiveBreaches,
	}
}

func (s *alertingService) getOrDefaultConfig(ctx context.Context, monitorID uuid.UUID) (*models.MonitorAlertConfig, error) {
	cfg, err := s.alertRepo.GetMonitorAlertConfig(ctx, monitorID)
	if err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return defaultMonitorAlertConfig(monitorID), nil
		}
		return nil, fmt.Errorf("failed to get monitor alert config: %w", err)
	}
	return cfg, nil
}

func (s *alertingService) GetMonitorAlertConfig(ctx context.Context, ouID, projectName, agentName, monitorName string) (*models.MonitorAlertConfig, bool, error) {
	monitor, err := s.loadMonitor(ouID, projectName, agentName, monitorName)
	if err != nil {
		return nil, false, err
	}
	cfg, err := s.getOrDefaultConfig(ctx, monitor.ID)
	if err != nil {
		return nil, false, err
	}
	configured, err := s.endpointEnabled(ctx, ouID)
	if err != nil {
		return nil, false, err
	}
	return cfg, configured, nil
}

func (s *alertingService) UpdateMonitorAlertConfig(
	ctx context.Context, ouID, projectName, agentName, monitorName string, cfg models.MonitorAlertConfig,
) (*models.MonitorAlertConfig, bool, error) {
	monitor, err := s.loadMonitor(ouID, projectName, agentName, monitorName)
	if err != nil {
		return nil, false, err
	}
	if err := validateMonitorAlertConfig(monitor, &cfg); err != nil {
		return nil, false, err
	}

	cfg.MonitorID = monitor.ID
	if err := s.alertRepo.UpsertMonitorAlertConfig(ctx, &cfg); err != nil {
		return nil, false, fmt.Errorf("failed to save monitor alert config: %w", err)
	}
	saved, err := s.getOrDefaultConfig(ctx, monitor.ID)
	if err != nil {
		return nil, false, err
	}
	configured, err := s.endpointEnabled(ctx, ouID)
	if err != nil {
		return nil, false, err
	}
	return saved, configured, nil
}

// validateMonitorAlertConfig checks rules against the monitor's evaluators and
// normalises defaults in place.
func validateMonitorAlertConfig(monitor *models.Monitor, cfg *models.MonitorAlertConfig) error {
	if cfg.CooldownMinutes < 0 || cfg.CooldownMinutes > maxAlertCooldownMinutes {
		return fmt.Errorf("%w: cooldownMinutes must be between 0 and %d", utils.ErrInvalidInput, maxAlertCooldownMinutes)
	}
	if cfg.ConsecutiveBreaches == 0 {
		cfg.ConsecutiveBreaches = models.DefaultAlertConsecutiveBreaches
	}
	if cfg.ConsecutiveBreaches < 1 || cfg.ConsecutiveBreaches > maxAlertConsecutive {
		return fmt.Errorf("%w: consecutiveBreaches must be between 1 and %d", utils.ErrInvalidInput, maxAlertConsecutive)
	}
	if len(cfg.Thresholds) > maxAlertThresholds {
		return fmt.Errorf("%w: at most %d thresholds are allowed", utils.ErrInvalidInput, maxAlertThresholds)
	}
	if cfg.Thresholds == nil {
		cfg.Thresholds = []models.MonitorAlertThreshold{}
	}

	evaluators := make(map[string]bool, len(monitor.Evaluators))
	for _, e := range monitor.Evaluators {
		evaluators[e.DisplayName] = true
	}
	seen := make(map[string]bool, len(cfg.Thresholds))
	for i := range cfg.Thresholds {
		t := &cfg.Thresholds[i]
		if !evaluators[t.Evaluator] {
			return fmt.Errorf("%w: evaluator %q is not configured on this monitor", utils.ErrInvalidInput, t.Evaluator)
		}
		if t.Aggregation == "" {
			return fmt.Errorf("%w: aggregation is required for evaluator %q", utils.ErrInvalidInput, t.Evaluator)
		}
		if t.Operator == "" {
			t.Operator = models.AlertOperatorLT
		}
		if t.Operator != models.AlertOperatorLT && t.Operator != models.AlertOperatorLTE {
			return fmt.Errorf("%w: operator must be %q or %q", utils.ErrInvalidInput, models.AlertOperatorLT, models.AlertOperatorLTE)
		}
		if t.Value < 0 || t.Value > 1 {
			return fmt.Errorf("%w: threshold for evaluator %q must be between 0 and 1", utils.ErrInvalidInput, t.Evaluator)
		}
		key := t.Evaluator + "\x00" + t.Aggregation
		if seen[key] {
			return fmt.Errorf("%w: duplicate threshold for evaluator %q aggregation %q", utils.ErrInvalidInput, t.Evaluator, t.Aggregation)
		}
		seen[key] = true
	}

	if cfg.Enabled && !cfg.AlertOnRunFailure && len(cfg.Thresholds) == 0 {
		return fmt.Errorf("%w: enable run-failure alerts or add at least one threshold", utils.ErrInvalidInput)
	}
	return nil
}

// ----------------------------------------------------------------------------
// Evaluation (called by the monitor scheduler)
// ----------------------------------------------------------------------------

func (s *alertingService) OnMonitorRunFinished(
	ctx context.Context, monitor *models.Monitor, run *models.MonitorRun, status, errorMessage string,
) {
	log := s.logger.With("ouID", monitor.OUID, "monitor", monitor.Name, "runID", run.ID)
	var err error
	switch status {
	case models.RunStatusFailed:
		err = s.alertRunFailed(ctx, monitor, run, errorMessage)
	case models.RunStatusSuccess:
		err = s.evaluateThresholds(ctx, monitor, run)
	default:
		return
	}
	if err != nil {
		log.Error("Failed to evaluate monitor alerts", "status", status, "error", err)
	}
}

func (s *alertingService) OnMonitorTriggerFailed(ctx context.Context, monitor *models.Monitor, cause error) {
	cfg, ok, err := s.activeConfig(ctx, monitor)
	if err != nil || !ok || !cfg.AlertOnRunFailure {
		if err != nil {
			s.logger.Error("Failed to evaluate monitor trigger alert", "monitor", monitor.Name, "error", err)
		}
		return
	}
	now := s.now()
	if inAlertCooldown(monitor, cfg, now) {
		return
	}
	reason := "failed to start the evaluation run"
	if cause != nil {
		reason = reason + ": " + cause.Error()
	}
	// No run row exists for a run that never started; the minute bucket plus
	// the cooldown keeps retries from producing duplicates.
	eventID := fmt.Sprintf("mon-start-failed-%s-%d", monitor.ID, now.Unix()/60)
	event := s.baseMonitorEvent(eventID, models.AlertEventMonitorRunFailed, models.AlertSeverityCritical, monitor, nil, now)
	event.Error = reason
	if err := s.enqueue(ctx, monitor, event); err != nil {
		s.logger.Error("Failed to enqueue monitor trigger alert", "monitor", monitor.Name, "error", err)
		return
	}
	if err := s.alertRepo.UpdateMonitorAlertState(ctx, monitor.ID, cfg.ConsecutiveBreachCount, &now); err != nil {
		s.logger.Error("Failed to record monitor alert state", "monitor", monitor.Name, "error", err)
	}
}

// activeConfig returns the monitor's config when alerting is enabled for it
// and the org has an enabled endpoint.
func (s *alertingService) activeConfig(ctx context.Context, monitor *models.Monitor) (*models.MonitorAlertConfig, bool, error) {
	cfg, err := s.alertRepo.GetMonitorAlertConfig(ctx, monitor.ID)
	if err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return nil, false, nil
		}
		return nil, false, fmt.Errorf("failed to get monitor alert config: %w", err)
	}
	if !cfg.Enabled {
		return cfg, false, nil
	}
	enabled, err := s.endpointEnabled(ctx, monitor.OUID)
	if err != nil {
		return nil, false, err
	}
	return cfg, enabled, nil
}

func (s *alertingService) alertRunFailed(ctx context.Context, monitor *models.Monitor, run *models.MonitorRun, errorMessage string) error {
	cfg, ok, err := s.activeConfig(ctx, monitor)
	if err != nil || !ok || !cfg.AlertOnRunFailure {
		return err
	}
	now := s.now()
	if inAlertCooldown(monitor, cfg, now) {
		s.logger.Debug("Monitor run-failure alert suppressed by cooldown", "monitor", monitor.Name, "runID", run.ID)
		return nil
	}
	event := s.baseMonitorEvent("mon-run-failed-"+run.ID.String(), models.AlertEventMonitorRunFailed,
		models.AlertSeverityCritical, monitor, run, now)
	event.Error = errorMessage
	if event.Error == "" {
		event.Error = "evaluation run failed"
	}
	if err := s.enqueue(ctx, monitor, event); err != nil {
		return err
	}
	return s.alertRepo.UpdateMonitorAlertState(ctx, monitor.ID, cfg.ConsecutiveBreachCount, &now)
}

func (s *alertingService) evaluateThresholds(ctx context.Context, monitor *models.Monitor, run *models.MonitorRun) error {
	cfg, ok, err := s.activeConfig(ctx, monitor)
	if err != nil || !ok || len(cfg.Thresholds) == 0 {
		return err
	}

	runEvaluators, err := s.scoreRepo.GetEvaluatorsByMonitorAndRunID(monitor.ID, run.ID)
	if err != nil {
		return fmt.Errorf("failed to load run scores: %w", err)
	}
	breaches := findThresholdBreaches(cfg.Thresholds, runEvaluators)

	if len(breaches) == 0 {
		if cfg.ConsecutiveBreachCount == 0 {
			return nil
		}
		return s.alertRepo.UpdateMonitorAlertState(ctx, monitor.ID, 0, nil)
	}

	count := cfg.ConsecutiveBreachCount + 1
	now := s.now()
	if count < cfg.ConsecutiveBreaches || inAlertCooldown(monitor, cfg, now) {
		return s.alertRepo.UpdateMonitorAlertState(ctx, monitor.ID, count, nil)
	}

	event := s.baseMonitorEvent("mon-breach-"+run.ID.String(), models.AlertEventMonitorThresholdBreached,
		models.AlertSeverityWarning, monitor, run, now)
	event.Breaches = breaches
	if err := s.enqueue(ctx, monitor, event); err != nil {
		return err
	}
	return s.alertRepo.UpdateMonitorAlertState(ctx, monitor.ID, count, &now)
}

// findThresholdBreaches compares each rule with the run's aggregated scores.
// An evaluator that scored nothing, or an aggregation that was not reported,
// is skipped: missing data is not a failing score.
func findThresholdBreaches(rules []models.MonitorAlertThreshold, runEvaluators []models.MonitorRunEvaluator) []models.AlertScoreBreach {
	byName := make(map[string]models.MonitorRunEvaluator, len(runEvaluators))
	for _, e := range runEvaluators {
		byName[e.EvaluatorName] = e
	}
	var breaches []models.AlertScoreBreach
	for _, rule := range rules {
		ev, ok := byName[rule.Evaluator]
		if !ok || ev.Count == 0 {
			continue
		}
		value, ok := aggregationValue(ev.Aggregations[rule.Aggregation])
		if !ok || !rule.Breached(value) {
			continue
		}
		breaches = append(breaches, models.AlertScoreBreach{
			Evaluator:   rule.Evaluator,
			Aggregation: rule.Aggregation,
			Value:       value,
			Threshold:   rule.Value,
			Operator:    rule.Operator,
			SampleCount: ev.Count,
		})
	}
	return breaches
}

func aggregationValue(raw interface{}) (float64, bool) {
	switch v := raw.(type) {
	case float64:
		return v, true
	case float32:
		return float64(v), true
	case int:
		return float64(v), true
	case int64:
		return float64(v), true
	case json.Number:
		f, err := v.Float64()
		return f, err == nil
	case string:
		f, err := strconv.ParseFloat(v, 64)
		return f, err == nil
	default:
		return 0, false
	}
}

// inAlertCooldown reports whether an alert for this monitor is suppressed.
// Only scheduled (future) monitors are throttled: they fail on every interval
// until fixed. A past monitor runs only when someone asks, so each failed or
// breached run, reruns included, alerts once.
func inAlertCooldown(monitor *models.Monitor, cfg *models.MonitorAlertConfig, now time.Time) bool {
	if monitor.Type != models.MonitorTypeFuture {
		return false
	}
	if cfg.LastAlertedAt == nil || cfg.CooldownMinutes <= 0 {
		return false
	}
	return now.Before(cfg.LastAlertedAt.Add(time.Duration(cfg.CooldownMinutes) * time.Minute))
}

func (s *alertingService) baseMonitorEvent(
	eventID, eventType, severity string, monitor *models.Monitor, run *models.MonitorRun, now time.Time,
) models.AlertEvent {
	info := &models.AlertMonitorInfo{Name: monitor.Name, DisplayName: monitor.DisplayName}
	if run != nil {
		start, end := run.TraceStart, run.TraceEnd
		info.RunID = run.ID.String()
		info.TraceStart = &start
		info.TraceEnd = &end
	}
	return models.AlertEvent{
		ID:          eventID,
		Type:        eventType,
		Version:     alertEventVersion,
		OccurredAt:  now.UTC(),
		Severity:    severity,
		OrgID:       monitor.OUID,
		Project:     monitor.ProjectName,
		Agent:       monitor.AgentName,
		Environment: monitor.EnvironmentName,
		Monitor:     info,
	}
}

func (s *alertingService) enqueue(ctx context.Context, monitor *models.Monitor, event models.AlertEvent) error {
	body, err := json.Marshal(event)
	if err != nil {
		return fmt.Errorf("failed to encode alert event: %w", err)
	}
	now := s.now()
	monitorID := monitor.ID
	created, err := s.alertRepo.EnqueueDelivery(ctx, &models.AlertDelivery{
		OUID:          monitor.OUID,
		EventID:       event.ID,
		EventType:     event.Type,
		MonitorID:     &monitorID,
		MonitorName:   monitor.Name,
		Payload:       string(body),
		Status:        models.AlertDeliveryStatusPending,
		NextAttemptAt: &now,
		CreatedAt:     now,
	})
	if err != nil {
		return fmt.Errorf("failed to enqueue alert: %w", err)
	}
	if created {
		s.logger.Info("Alert queued", "ouID", monitor.OUID, "monitor", monitor.Name, "eventType", event.Type, "eventID", event.ID)
	}
	return nil
}

