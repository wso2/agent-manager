const (
	alertEventVersion       = "1"
	alertSigningSecretBytes = 32
	alertSigningSecretPfx   = "whsec_"
	maxAlertThresholds      = 50
	maxAlertCooldownMinutes = 7 * 24 * 60
	maxAlertConsecutive     = 100
	maxAlertHeaders         = 20
	defaultDeliveryPageSize = 50
	maxDeliveryPageSize     = 100
)

// UpsertAlertEndpointInput is the validated input for saving an org endpoint.
type UpsertAlertEndpointInput struct {
	URL     string
	Enabled bool
	// Headers replaces the stored headers when non-nil; nil keeps them.
	Headers                 map[string]string
	RegenerateSigningSecret bool
}

// AlertTestResult reports the outcome of a synchronous test delivery.
type AlertTestResult struct {
	Delivered  bool
	StatusCode int
	Error      string
}

// AlertingService manages the org alert endpoint and per-monitor alert rules.
type AlertingService interface {
	GetEndpoint(ctx context.Context, ouID string) (*models.AlertEndpoint, error)
	// UpsertEndpoint saves the endpoint. The returned secret is non-empty only
	// when one was generated by this call.
	UpsertEndpoint(ctx context.Context, ouID string, in UpsertAlertEndpointInput) (*models.AlertEndpoint, string, error)
	DeleteEndpoint(ctx context.Context, ouID string) error
	TestEndpoint(ctx context.Context, ouID string) (*AlertTestResult, error)
	ListDeliveries(ctx context.Context, ouID string, limit int) ([]models.AlertDelivery, error)

	// GetMonitorAlertConfig returns the monitor's config (a disabled default if
	// none is stored) and whether the org has an enabled endpoint.
	GetMonitorAlertConfig(ctx context.Context, ouID, projectName, agentName, monitorName string) (*models.MonitorAlertConfig, bool, error)
	UpdateMonitorAlertConfig(ctx context.Context, ouID, projectName, agentName, monitorName string, cfg models.MonitorAlertConfig) (*models.MonitorAlertConfig, bool, error)

	MonitorRunAlerter
}

// MonitorRunAlerter is the narrow surface the monitor scheduler uses to raise
// alerts. Implementations must not fail the caller: errors are logged.
type MonitorRunAlerter interface {
	// OnMonitorRunFinished is called once a run reaches a terminal status.
	OnMonitorRunFinished(ctx context.Context, monitor *models.Monitor, run *models.MonitorRun, status, errorMessage string)
	// OnMonitorTriggerFailed is called when a scheduled run could not be started.
	OnMonitorTriggerFailed(ctx context.Context, monitor *models.Monitor, cause error)
}

type alertingService struct {
	alertRepo     repositories.AlertRepository
	monitorRepo   repositories.MonitorRepository
	scoreRepo     repositories.ScoreRepository
	sender        AlertSender
	encryptionKey []byte
	logger        *slog.Logger
	now           func() time.Time
}

// NewAlertingService creates the alerting service.
func NewAlertingService(
	alertRepo repositories.AlertRepository,
	monitorRepo repositories.MonitorRepository,
	scoreRepo repositories.ScoreRepository,
	sender AlertSender,
	encryptionKey []byte,
	logger *slog.Logger,
) AlertingService {
	return newAlertingService(alertRepo, monitorRepo, scoreRepo, sender, encryptionKey, logger)
}

func newAlertingService(
	alertRepo repositories.AlertRepository,
	monitorRepo repositories.MonitorRepository,
	scoreRepo repositories.ScoreRepository,
	sender AlertSender,
	encryptionKey []byte,
	logger *slog.Logger,
) *alertingService {
	return &alertingService{
		alertRepo:     alertRepo,
		monitorRepo:   monitorRepo,
		scoreRepo:     scoreRepo,
		sender:        sender,
		encryptionKey: encryptionKey,
		logger:        logger,
		now:           time.Now,
	}
}

