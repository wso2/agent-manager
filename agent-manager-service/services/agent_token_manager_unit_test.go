func TestNewAgentTokenManagerService(t *testing.T) {
	oc := &clientmocks.OpenChoreoClientMock{}

	t.Run("succeeds with valid key configuration", func(t *testing.T) {
		cfg := testJWTConfig()
		if _, err := os.Stat(cfg.PrivateKeyPath); err != nil {
			t.Skipf("signing keys not present (%v); run scripts/gen_keys.sh", err)
		}
		svc, err := NewAgentTokenManagerService(oc, cfg, discardLogger())
		require.NoError(t, err)
		require.NotNil(t, svc)
	})

	t.Run("fails when the private key file is missing", func(t *testing.T) {
		cfg := testJWTConfig()
		cfg.PrivateKeyPath = "../keys/does-not-exist.pem"
		_, err := NewAgentTokenManagerService(oc, cfg, discardLogger())
		require.Error(t, err)
	})

	t.Run("fails when the public keys config is missing", func(t *testing.T) {
		cfg := testJWTConfig()
		if _, err := os.Stat(cfg.PrivateKeyPath); err != nil {
			t.Skipf("signing keys not present (%v); run scripts/gen_keys.sh", err)
		}
		cfg.PublicKeysConfigPath = "../keys/no-such-config.json"
		_, err := NewAgentTokenManagerService(oc, cfg, discardLogger())
		require.Error(t, err)
	})

	t.Run("fails when active key id is absent from loaded keys", func(t *testing.T) {
		cfg := testJWTConfig()
		if _, err := os.Stat(cfg.PrivateKeyPath); err != nil {
			t.Skipf("signing keys not present (%v); run scripts/gen_keys.sh", err)
		}
		cfg.ActiveKeyID = "key-does-not-exist"
		_, err := NewAgentTokenManagerService(oc, cfg, discardLogger())
		require.Error(t, err)
	})
}

