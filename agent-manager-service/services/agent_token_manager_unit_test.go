func TestAgentTokenManager_GenerateToken_HappyPath(t *testing.T) {
	oc := fullClientMock("comp-uuid", "env-uuid", "proj-uuid")
	svc := newTokenManager(t, oc)

	req := GenerateTokenRequest{
		OrgName:     "acme",
		ProjectName: "proj",
		AgentName:   "my-agent",
		Environment: "dev",
		OrgId:       "org-123",
		ExpiresIn:   "1h",
	}

	resp, err := svc.GenerateToken(context.Background(), req)

	require.NoError(t, err)
	require.NotNil(t, resp)
	assert.Equal(t, "Bearer", resp.TokenType)
	assert.NotEmpty(t, resp.Token)
	assert.Greater(t, resp.ExpiresAt, resp.IssuedAt, "token must expire after it is issued")

	// Parse the token (without verifying the signature here) and assert that the
	// claims were assembled from the looked-up UUIDs and request fields.
	parser := jwt.NewParser()
	claims := &AgentTokenClaims{}
	parsed, _, err := parser.ParseUnverified(resp.Token, claims)
	require.NoError(t, err)

	assert.Equal(t, "comp-uuid", claims.ComponentUid)
	assert.Equal(t, "env-uuid", claims.EnvironmentUid)
	assert.Equal(t, "proj-uuid", claims.ProjectUid)
	assert.Equal(t, "org-123", claims.OrgId)
	assert.Equal(t, "acme-namespace", claims.Namespace, "namespace claim must come from GetOrganization, not the raw OU id")
	assert.Equal(t, "my-agent", claims.Subject)
	assert.Equal(t, "agent-manager-test", claims.Issuer)
	assert.NotEmpty(t, claims.ID, "jti claim must be set for forward-compatible revocation")
	assert.Equal(t, "key-1", parsed.Header["kid"])
	assert.Equal(t, "RS256", parsed.Method.Alg())
}

